import fs from 'node:fs';
import assert from 'node:assert/strict';
const source=fs.readFileSync(new URL('../assets/bubble-lifetime.js',import.meta.url),'utf8');
const {BubbleLifetime}=await import('data:text/javascript;base64,'+Buffer.from(source).toString('base64'));
const lifetime=new BubbleLifetime();
assert.equal(lifetime.sync('library-1',false,0),'hidden');
assert.equal(lifetime.started,null,'An offscreen avatar must not start a greeting.');
assert.equal(lifetime.sync('library-1',true,100),'visible');
assert.equal(lifetime.sync('library-1',true,2849),'visible');
assert.equal(lifetime.sync('library-1',true,2850),'fading');
assert.equal(lifetime.sync('library-1',true,3100),'expired');
assert.equal(lifetime.sync('library-1',true,6000),'hidden','Expired greetings must not repeat.');
assert.equal(lifetime.sync('library-2',true,7000),'visible','A new visit can greet once.');
lifetime.dismiss();
assert.equal(lifetime.sync('library-2',true,7100),'hidden','The X stays dismissed for this visit.');
assert.equal(lifetime.sync('controls-3',true,8000),'visible');
assert.equal(lifetime.sync('controls-3',false,8100),'hidden','Looking away or hiding the owner dismisses immediately.');
assert.equal(lifetime.sync('controls-3',true,8200),'hidden','Reappearing cannot resurrect an old bubble.');
console.log('PASS: 3-second deadline, fade window, manual close, offscreen dismissal, and visit generations.');
